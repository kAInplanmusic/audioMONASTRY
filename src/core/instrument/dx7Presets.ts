import type { Dx7Patch, Dx7OperatorParams } from './fmEngine';

function op(
  ratio: number,
  level: number,
  rates: [number, number, number, number] = [95, 80, 70, 60],
  levels: [number, number, number, number] = [99, 80, 60, 0],
  detune = 0,
  velSens = 3,
): Dx7OperatorParams {
  return { ratio, fixed: false, fixedHz: 0, level, rates, levels, detune, velocitySensitivity: velSens, keyScaling: 0 };
}

function patch(name: string, algorithm: number, feedback: number, ops: Dx7OperatorParams[]): Dx7Patch {
  return {
    name,
    algorithm,
    feedback,
    transpose: 0,
    lfo: { speedHz: 0, delaySec: 0, pitchModDepth: 0, ampModDepth: 0, sync: false },
    operators: ops as Dx7Patch['operators'],
  };
}

