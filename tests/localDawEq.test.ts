import { beforeEach, expect, it, vi } from 'vitest';
import { BackendMainProcessors } from '../server/backendMainProcessors';
import { requestDawPlan } from '../src/core/ai/clientDawExecutor';
import { voiceControlService } from '../src/core/voice/VoiceControlService';
import '../src/core/voice/pluginCommandRegistry';

const deps = vi.hoisted(() => ({
  holder: vi.fn(),
  read: vi.fn(),
  write: vi.fn(),
  audio: vi.fn(),
  flush: vi.fn(),
}));

vi.mock('../src/utils/pluginSettings', () => ({
  isPluginSettingsHolder: deps.holder,
  readPluginSettings: deps.read,
  writePluginSettings: deps.write,
  flushPluginSettings: deps.flush,
}));
vi.mock('../src/utils/audioEngine', () => ({
  audioEngine: { updateToneShiftEQ: deps.audio },
}));

beforeEach(() => {
  vi.resetAllMocks();
  deps.holder.mockReturnValue(true);
});

it('dispatches the canonical command and shifts only the three lowest gains', async () => {
  deps.read.mockReturnValue({ gains: [11, -5, 2, 6, ...Array(32).fill(0)], qs: [0.8], power: true });
  const [step] = (await requestDawPlan('Equalizer Bass zwei höher')).steps;
  const result = await voiceControlService.executePluginCommand('localUser', step.pluginId, step.command);
  expect(result.handled).toBe(true);
  const update = deps.audio.mock.calls[0][0];
  expect(update.bands).toHaveLength(36);
  expect(update.bands.slice(0, 4).map((band: { gain: number }) => band.gain)).toEqual([12, -3, 4, 6]);
  expect(update.bands[0].q).toBe(0.8);
  expect(deps.write.mock.calls[0][1].gains.slice(0, 4)).toEqual([12, -3, 4, 6]);
});

it('refuses writes without the EQ lock or while the EQ is bypassed', async () => {
  deps.holder.mockReturnValueOnce(false);
  deps.read.mockReturnValue({ power: false });
  for (const message of ['übernehmen', 'aktivieren']) {
    const result = await voiceControlService.executePluginCommand('localUser', 'eq', 'shift_gain(1-3, 2)');
    expect(result.handled).toBe(false);
    expect(result.error).toContain(message);
  }
  expect(deps.audio).not.toHaveBeenCalled();
  expect(deps.write).not.toHaveBeenCalled();
});

it('writes the twelve-band Main master through its existing authorized settings section', async () => {
  deps.read.mockReturnValue({ gain: 0.8, bands: [23, -2, 1, 4] });
  const [step] = (await requestDawPlan('Master EQ Bass zwei höher')).steps;
  const result = await voiceControlService.executePluginCommand('localUser', step.pluginId, step.command);
  expect(result.handled).toBe(true);
  expect(deps.holder).toHaveBeenCalledWith('master');
  expect(deps.write).toHaveBeenCalledWith('master', { gain: 0.8, bands: [24, 0, 3, 4, ...Array(8).fill(0)] },
    { section: 'backendMain' });
  expect(deps.flush).toHaveBeenCalledWith('master');
  expect(deps.audio).not.toHaveBeenCalled();
});

it('renders a measurable bass boost from the settings generated by the local command', async () => {
  const [step] = (await requestDawPlan('Master EQ Bass zwei höher')).steps;
  const result = await voiceControlService.executePluginCommand('localUser', step.pluginId, step.command);
  expect(result.handled).toBe(true);
  const parameters = deps.write.mock.calls[0][1];
  const input = Float32Array.from({ length: 48_000 }, (_, index) =>
    0.1 * Math.sin(2 * Math.PI * 80 * Math.floor(index / 2) / 48_000));
  const rms = (block: Float32Array) => Math.sqrt(
    block.reduce((sum, value) => sum + value ** 2, 0) / block.length);
  const processed = new BackendMainProcessors(48_000).process(new Map([['song', input]]), {
    master: { active: true, parameters, epoch: 1 },
  });
  expect(rms(processed.subarray(8192)) / rms(input.subarray(8192))).toBeGreaterThan(1.2);
});
